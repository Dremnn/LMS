CREATE TRIGGER trg_enrollment_update_total_students
AFTER INSERT OR DELETE OR UPDATE OF course_id ON enrollments
FOR EACH ROW EXECUTE FUNCTION trg_enrollment_update_total_students_fn();

-- Trigger Function: Cập nhật tổng số bài học trong khóa học
CREATE OR REPLACE FUNCTION trg_lesson_update_total_lessons_fn()
RETURNS TRIGGER 
LANGUAGE plpgsql 
AS $$
DECLARE
    v_course_id INTEGER;
BEGIN
    SELECT course_id INTO v_course_id 
    FROM sections 
    WHERE id = (CASE WHEN TG_OP = 'DELETE' THEN OLD.section_id ELSE NEW.section_id END);

    IF v_course_id IS NOT NULL THEN
        UPDATE courses
        SET total_lessons = (
            SELECT COUNT(*) FROM lessons l 
            INNER JOIN sections s ON l.section_id = s.id 
            WHERE s.course_id = v_course_id
        )
        WHERE id = v_course_id;
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.section_id IS DISTINCT FROM NEW.section_id THEN
        SELECT course_id INTO v_course_id FROM sections WHERE id = OLD.section_id;
        IF v_course_id IS NOT NULL THEN
            UPDATE courses
            SET total_lessons = (
                SELECT COUNT(*) FROM lessons l 
                INNER JOIN sections s ON l.section_id = s.id 
                WHERE s.course_id = v_course_id
            )
            WHERE id = v_course_id;
        END IF;
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;


