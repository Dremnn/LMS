-- Trigger Function: Cập nhật tiến độ khi thay đổi lesson_progress
CREATE OR REPLACE FUNCTION trg_lesson_progress_update_fn()
RETURNS TRIGGER 
LANGUAGE plpgsql 
AS $$
DECLARE
    v_enrollment_id INTEGER;
    v_new_progress  NUMERIC(5,2);
BEGIN
    v_enrollment_id := NEW.enrollment_id;
    v_new_progress := fn_calculate_progress(v_enrollment_id);

    UPDATE enrollments
    SET progress_percent = v_new_progress,
        status = CASE WHEN v_new_progress >= 100 THEN 'completed' ELSE 'in_progress' END,
        completed_at = CASE WHEN v_new_progress >= 100 AND completed_at IS NULL THEN CURRENT_TIMESTAMP ELSE completed_at END
    WHERE id = v_enrollment_id;

    IF TG_OP = 'UPDATE' AND OLD.enrollment_id IS DISTINCT FROM NEW.enrollment_id THEN
        v_new_progress := fn_calculate_progress(OLD.enrollment_id);
        UPDATE enrollments
        SET progress_percent = v_new_progress,
            status = CASE WHEN v_new_progress >= 100 THEN 'completed' ELSE 'in_progress' END
        WHERE id = OLD.enrollment_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_lesson_progress_update ON lesson_progress;
CREATE TRIGGER trg_lesson_progress_update
AFTER INSERT OR UPDATE ON lesson_progress
FOR EACH ROW EXECUTE FUNCTION trg_lesson_progress_update_fn();

-- Trigger Function: Cập nhật tổng số học viên trong khóa học
CREATE OR REPLACE FUNCTION trg_enrollment_update_total_students_fn()
RETURNS TRIGGER 
LANGUAGE plpgsql 
AS $$
DECLARE
    v_course_id INTEGER;
BEGIN
    v_course_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.course_id ELSE NEW.course_id END;

    UPDATE courses
    SET total_students = (SELECT COUNT(*) FROM enrollments WHERE course_id = v_course_id)
    WHERE id = v_course_id;

    IF TG_OP = 'UPDATE' AND OLD.course_id IS DISTINCT FROM NEW.course_id THEN
        UPDATE courses
        SET total_students = (SELECT COUNT(*) FROM enrollments WHERE course_id = OLD.course_id)
        WHERE id = OLD.course_id;
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_enrollment_update_total_students ON enrollments;
CREATE TRIGGER trg_enrollment_update_total_students
AFTER INSERT OR DELETE OR UPDATE OF course_id ON enrollments
FOR EACH ROW EXECUTE FUNCTION trg_enrollment_update_total_students_fn();

-- Trigger Function: Cập nhật tổng số bài học trong khóa học
CREATE OR REPLACE FUNCTION trg_lesson_update_total_lessons_fn()
RETURNS TRIGGER 
LANGUAGE plpgsql 
AS $$
DECLARE
    v_course_id INTEGER;
BEGIN
    SELECT course_id INTO v_course_id 
    FROM sections 
    WHERE id = (CASE WHEN TG_OP = 'DELETE' THEN OLD.section_id ELSE NEW.section_id END);

    IF v_course_id IS NOT NULL THEN
        UPDATE courses
        SET total_lessons = (
            SELECT COUNT(*) FROM lessons l 
            INNER JOIN sections s ON l.section_id = s.id 
            WHERE s.course_id = v_course_id
        )
        WHERE id = v_course_id;
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.section_id IS DISTINCT FROM NEW.section_id THEN
        SELECT course_id INTO v_course_id FROM sections WHERE id = OLD.section_id;
        IF v_course_id IS NOT NULL THEN
            UPDATE courses
            SET total_lessons = (
                SELECT COUNT(*) FROM lessons l 
                INNER JOIN sections s ON l.section_id = s.id 
                WHERE s.course_id = v_course_id
            )
            WHERE id = v_course_id;
        END IF;
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

