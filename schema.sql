FOR EACH ROW EXECUTE FUNCTION trg_lesson_progress_update_fn();

-- Trigger Function: Cập nhật tổng số học viên trong khóa học
CREATE OR REPLACE FUNCTION trg_enrollment_update_total_students_fn()
RETURNS TRIGGER 
LANGUAGE plpgsql 
AS $$
DECLARE
    v_course_id INTEGER;
BEGIN
    v_course_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.course_id ELSE NEW.course_id END;

    UPDATE courses
    SET total_students = (SELECT COUNT(*) FROM enrollments WHERE course_id = v_course_id)
    WHERE id = v_course_id;

    IF TG_OP = 'UPDATE' AND OLD.course_id IS DISTINCT FROM NEW.course_id THEN
        UPDATE courses
        SET total_students = (SELECT COUNT(*) FROM enrollments WHERE course_id = OLD.course_id)
        WHERE id = OLD.course_id;
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

