-- Trigger Function: Cập nhật tiến độ khi thay đổi lesson_progress
CREATE OR REPLACE FUNCTION trg_lesson_progress_update_fn()
RETURNS TRIGGER 
LANGUAGE plpgsql 
AS $$
DECLARE
    v_enrollment_id INTEGER;
    v_new_progress  NUMERIC(5,2);
BEGIN
    v_enrollment_id := NEW.enrollment_id;
    v_new_progress := fn_calculate_progress(v_enrollment_id);

    UPDATE enrollments
    SET progress_percent = v_new_progress,
        status = CASE WHEN v_new_progress >= 100 THEN 'completed' ELSE 'in_progress' END,
        completed_at = CASE WHEN v_new_progress >= 100 AND completed_at IS NULL THEN CURRENT_TIMESTAMP ELSE completed_at END
    WHERE id = v_enrollment_id;

    IF TG_OP = 'UPDATE' AND OLD.enrollment_id IS DISTINCT FROM NEW.enrollment_id THEN
        v_new_progress := fn_calculate_progress(OLD.enrollment_id);
        UPDATE enrollments
        SET progress_percent = v_new_progress,
            status = CASE WHEN v_new_progress >= 100 THEN 'completed' ELSE 'in_progress' END
        WHERE id = OLD.enrollment_id;
    END IF;

    RETURN NEW;
END;
$$;

