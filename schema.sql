-- Tính % tiến độ học tập của một enrollment
CREATE OR REPLACE FUNCTION fn_calculate_progress(p_enrollment_id INTEGER)
RETURNS NUMERIC(5,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_course_id          INTEGER;
    v_total_lessons      INTEGER;
    v_completed_lessons  INTEGER;
    v_result             NUMERIC(5,2);
BEGIN
    SELECT course_id INTO v_course_id FROM enrollments WHERE id = p_enrollment_id;

    IF v_course_id IS NULL THEN
        RETURN 0;
    END IF;

    SELECT COUNT(*) INTO v_total_lessons
    FROM lessons l
    INNER JOIN sections s ON l.section_id = s.id
    WHERE s.course_id = v_course_id;

    SELECT COUNT(*) INTO v_completed_lessons
    FROM lesson_progress
    WHERE enrollment_id = p_enrollment_id AND is_completed = TRUE;

    IF v_total_lessons IS NULL OR v_total_lessons = 0 THEN
        v_result := 0;
    ELSE
        v_result := (v_completed_lessons::NUMERIC / v_total_lessons) * 100;
    END IF;

    RETURN ROUND(v_result, 2);
END;
$$;

-- Sinh mã chứng chỉ tự động: CERT-{course_id}-{student_id}-{yyyyMMddHHmmss}
CREATE OR REPLACE FUNCTION fn_generate_certificate_code(p_student_id INTEGER, p_course_id INTEGER)
RETURNS VARCHAR(50)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN 'CERT-' || p_course_id || '-' || p_student_id || '-' || TO_CHAR(CURRENT_TIMESTAMP, 'YYYYMMDDHH24MISS');
END;
$$;

